#!/usr/bin/env node
/**
 * Generate src/lib/assets/domain-grids.ts, the grid spacing of every data
 * domain, from the weather-map-layer domain table.
 *
 * The bounding box form sizes its default box in grid cells, which needs the
 * spacing of each model's grid. The API publishes no spacing (meta.json only
 * carries the CRS and the extent), while weather-map-layer mirrors the backend
 * grids for its tiles, so its table is the source. The package itself is not a
 * dependency of the site: it bundles maplibre-gl and the file reader, far more
 * than a table of grids. Instead this downloads the pinned `src/domains.ts`
 * from GitHub; the file is plain data with a type-only import, so Node's
 * TypeScript type stripping loads it as is.
 *
 * Regular lat/lon grids keep their spacing in degrees. Every other grid is
 * expressed in kilometres, since its spacing in degrees changes with latitude:
 *   - grids with a projected origin state dx/dy in metres, or in rotated
 *     degrees for rotated lat/lon grids,
 *   - grids defined by their corner coordinates spread (nx - 1, ny - 1) equal
 *     cells along the diagonal between the corners,
 *   - gaussian grids have 90° / N latitude lines per hemisphere.
 *
 * The output is committed so the site builds without this script. Rerun it
 * when weather-map-layer gains or changes domains:
 *
 *   npm run domain-grids                    # WML_VERSION below
 *   node scripts/domain-grids.mjs 0.3.0     # another release tag
 */
import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const WML_VERSION = '0.2.2';

const version = process.argv[2] ?? WML_VERSION;
const SOURCE = `https://raw.githubusercontent.com/open-meteo/weather-map-layer/v${version}/src/domains.ts`;
const OUT = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'../src/lib/assets/domain-grids.ts'
);

const EARTH_RADIUS_KM = 6371;
const KM_PER_DEGREE = (2 * Math.PI * EARTH_RADIUS_KM) / 360;
const toRadians = (degrees) => (degrees * Math.PI) / 180;

/** Great-circle distance between two points in kilometres. */
const distanceKm = (a, b) => {
	const dLat = toRadians(b.lat - a.lat);
	const dLon = toRadians(b.lon - a.lon);
	const h =
		Math.sin(dLat / 2) ** 2 +
		Math.cos(toRadians(a.lat)) * Math.cos(toRadians(b.lat)) * Math.sin(dLon / 2) ** 2;
	return 2 * EARTH_RADIUS_KM * Math.asin(Math.sqrt(h));
};

const round = (value) => Number(value.toPrecision(6));
const km = (dx, dy = dx) => ({ unit: 'km', dx: round(dx), dy: round(dy) });

const spacing = (grid) => {
	switch (grid.type) {
		case 'regular': {
			if (grid.dx !== undefined && grid.dy !== undefined) {
				return { unit: 'degrees', dx: Math.abs(grid.dx), dy: Math.abs(grid.dy) };
			}
			// defined by its extent: the points span the extent inclusive of both ends
			const [latMin, latMax] = grid.latitude;
			const [lonMin, lonMax] = grid.longitude;
			return {
				unit: 'degrees',
				dx: round((lonMax - lonMin) / (grid.nx - 1)),
				dy: round((latMax - latMin) / (grid.ny - 1))
			};
		}
		case 'gaussian':
			return km((90 / grid.gaussianGridLatitudeLines) * KM_PER_DEGREE);
		case 'projectedFromGeographicOrigin':
		case 'projectedFromProjectedOrigin': {
			const scale = grid.projection.name === 'RotatedLatLonProjection' ? KM_PER_DEGREE : 1 / 1000;
			return km(grid.dx * scale, grid.dy * scale);
		}
		case 'projectedFromBounds': {
			const [latMin, latMax] = grid.latitude;
			const [lonMin, lonMax] = grid.longitude;
			const diagonal = distanceKm({ lat: latMin, lon: lonMin }, { lat: latMax, lon: lonMax });
			return km(diagonal / Math.hypot(grid.nx - 1, grid.ny - 1));
		}
		default:
			throw new Error(`unknown grid type ${grid.type}`);
	}
};

const response = await fetch(SOURCE);
if (!response.ok) {
	throw new Error(`${SOURCE}: ${response.status} ${response.statusText}`);
}
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'domain-grids-'));
const module = path.join(directory, 'domains.mjs');
fs.writeFileSync(module, stripTypeScriptTypes(await response.text()));
const { domainOptions } = await import(pathToFileURL(module).href);
fs.rmSync(directory, { recursive: true });

const entries = domainOptions
	.filter((domain) => domain.type !== 'seamless')
	.map((domain) => [domain.value, domain.label, spacing(domain.grid)])
	.sort(([a], [b]) => a.localeCompare(b));

const lines = entries.map(
	([value, label, { unit, dx, dy }]) =>
		`\t${value}: { label: '${label.replaceAll("'", "\\'")}', unit: '${unit}', dx: ${dx}, dy: ${dy} },`
);

fs.writeFileSync(
	OUT,
	`// Generated by scripts/domain-grids.mjs from weather-map-layer v${version} - do not edit by hand.
//
// Grid spacing of every Open-Meteo data domain, keyed by the domain value shared
// by the API and weather-map-layer. Regular lat/lon grids are in degrees;
// projected and gaussian grids are in kilometres, since their spacing in
// degrees changes with latitude.
export interface DomainGrid {
	label: string;
	unit: 'degrees' | 'km';
	dx: number;
	dy: number;
}

export const DOMAIN_GRIDS: Record<string, DomainGrid> = {
${lines.join('\n')}
};
`
);

const units = entries.reduce((count, [, , { unit }]) => {
	count[unit] = (count[unit] ?? 0) + 1;
	return count;
}, {});
console.log(`wrote ${entries.length} domains to ${path.relative(process.cwd(), OUT)}`, units);
